import {chromium,expect} from '@playwright/test';
import fs from 'node:fs';
const browser=await chromium.launch();
const page=await browser.newPage();
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8791');
const analyze=page.getByRole('button',{name:'Analyze text',exact:true});
await expect(analyze).toBeEnabled({timeout:30000});
await analyze.click();
await expect(page.locator('.token-trace button').first()).toBeVisible();
await page.getByLabel('Prompt',{exact:true}).fill('1 + 1 = 2\n2 + 2 = 4\n3 + 3 =');
await analyze.click();
await expect(page.locator('.token-trace button')).toHaveCount(16,{timeout:30000});
const evidence={errors,bodyText:await page.locator('body').innerText()};
fs.writeFileSync('exploration/prompt-switch-check.json',JSON.stringify(evidence,null,2));
console.log(JSON.stringify(evidence));
await browser.close();
if(errors.length) throw Error(errors.join('\n'));
